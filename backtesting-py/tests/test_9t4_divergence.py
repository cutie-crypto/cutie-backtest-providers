@pytest.mark.parametrize('name', NAMES)
def test_http_raw_details_and_frozen_result_v2_keys(name,monkeypatch,tmp_path):
    data=hand_frame()
    monkeypatch.setattr(p,'AUTH_TOKEN','')
    monkeypatch.setattr(p,'REPORTS_DIR',tmp_path)
    monkeypatch.setattr(p,'_fetch_ohlcv',lambda *a:data.copy())
    requested = []
    def warmup(*args):
        requested.append(args[5])
        return data.iloc[:0].copy()
    monkeypatch.setattr(p,'_fetch_template_warmup',warmup)
    monkeypatch.setattr(Backtest,'plot',lambda *a,**kw:None)
    result=TestClient(p.app).post('/cutie/backtest',json=request(name,hand_params(name))).json()
    assert result['result_status']=='success',result
    assert requested == [76 if name.startswith('macd') else 71]
    assert len(result['trades'])==1
    assert result['raw_report']['divergence']['setups'][0]['l2_index']==21
    assert result['raw_report']['divergence']['entries'][0]['frozen_target']==pytest.approx(144.156)
    assert result['assumptions']['divergence_execution']['indicator_sample']=='swing_low_bar'
    # Independent frozen contract baseline, not a key set derived from new response.
    assert set(result['metrics'])=={'total_return','max_drawdown','trade_count'}
    assert set(result['trades'][0])=={'seq','opened_at','closed_at','side','qty','entry_price','exit_price','fee','slippage','pnl'}
    for node in ('metrics','equity_curve','trades','data_manifest'):
        assert 'divergence' not in str(result[node])


