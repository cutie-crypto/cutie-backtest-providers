NAMES = ('macd_bullish_divergence', 'rsi_bullish_divergence')


def hand_params(name):
    values = dict(swing_n=2)
    if name.startswith('macd'):
        values.update(fast=2, slow=3, signal=2)
    else:
        values.update(rsi_period=2)
    return values


def hand_frame(size=64):
    # L1=13 (Low79, Close80), L2=21 (Low78, Close90), gap8; N2 => confirms23.
    # EMA alpha2/3 and 1/2; DEA alpha2/3. At22 DIF<=DEA; at23 DIF>DEA.
    closes = [100.]*12+[90,80,90,95,96,96,94,92,91,90,89,94,94,110,110,110]
    closes += [110.]*(size-len(closes))
    data = pd.DataFrame(dict(Open=closes, High=np.array(closes)+1, Low=np.array(closes)-1,
                             Close=closes, Volume=100.),
                        index=pd.date_range('2026-01-01', periods=size, freq='h'))
    data.iloc[21, 2] = 78.
    data.iloc[24, 0] = 100.
    data.iloc[24, 1] = 101.
    return data


def run(name, data=None, *, warm=0, **values):
    data = hand_frame() if data is None else data
    cls = p.TOOL_SPECS['local.backtesting_py.'+name]['build']({**hand_params(name), **values})['strategy']
    cls._warmup_bars = warm
    cls._warmup_cols = {c: data[c].iloc[:warm].to_numpy() for c in p._WARMUP_COLUMNS}
    main = data.iloc[warm:].copy()
    if cls._time_config is not None:
        cls._time_context = TimeContext.build(cls._time_config, '1h', main.index)
    return Backtest(main, cls, cash=100000, exclusive_orders=True, finalize_trades=True).run()


def facts(data=None, *, kind='macd', values=None, dif=None, dea=None, **config):
    data = hand_frame() if data is None else data
    # Test doubles are scalar, fixed indicator facts, never generated by subject.
    if values is None:
        values = [40.]*max(24,len(data))
        values[13], values[21] = (10., 20.) if kind=='rsi' else (-3., -1.)
    if dif is None:
        dif = [-1.]*len(data)
        dif[23:] = [1.]*(len(data)-23)
    dea = [0.]*len(data) if dea is None else dea
    return divergence_signals(*(data[c].to_numpy() for c in ('High','Low','Close')), values,
                              kind=kind, n=2, dif=dif, dea=dea, **config)


@pytest.mark.parametrize('name', NAMES)
@pytest.mark.parametrize('warm', [0, 10])
def test_hand_low_bar_values_and_next_open(name, warm):
    result = run(name, warm=warm)
    entries = result['_strategy'].divergence_report['entries']
    assert len(entries) == 1
    assert entries[0] == dict(setup=0, entry_bar=24-warm, entry_price=100.,
                             frozen_stop=pytest.approx(77.922), frozen_target=pytest.approx(144.156))
    setup = result['_strategy'].divergence_report['setups'][0]
    assert (setup['l1_index'], setup['l2_index'], setup['confirmed_at'], setup['signal_bar']) == (13,21,23,23)
    assert (setup['l1_price'], setup['l2_price']) == (79.,78.)
    if name.startswith('macd'):
        assert setup['l1_indicator'] == pytest.approx(-55/18)
        assert setup['l2_indicator'] == pytest.approx(-.5218417318138364)
        assert result['_trades'][['EntryBar','ExitBar']].values.tolist() == [[24-warm,28-warm]]
    else:
        assert setup['l1_indicator'] == 0
        assert setup['l2_indicator'] == pytest.approx(7.511737089201878)
        assert result['_trades'][['EntryBar','ExitBar']].values.tolist() == [[24-warm,25-warm]]


@pytest.mark.parametrize('kind', ['macd','rsi'])
def test_unconfirmed_second_low_never_signals_and_prefix_is_causal(kind):
    data = hand_frame()
    dif = [-1.]*len(data)
    dif[22] = 1.  # Early cross one bar before L2's right N bars have closed.
    dif[24:] = [1.]*(len(data)-24)
    full, _ = facts(data, kind=kind, dif=dif)
    assert all(full[i] is None for i in (21,22))
    assert full[23 if kind=='rsi' else 24] is not None
    for end in (21,22,23,24,25,29):
        part, _ = facts(data.iloc[:end], kind=kind, dif=dif[:end])
        assert part == full[:end]
    changed = data.copy()
    changed.iloc[25:, :4] = [500,501,499,500]
    assert facts(changed, kind=kind, dif=dif)[0][:25] == full[:25]


