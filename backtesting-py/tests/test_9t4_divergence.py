def test_independent_indicator_goldens_and_causal_tail():
    dif,dea,hist=macd_values([100.,90.,80.,90.],2,3,2)
    np.testing.assert_allclose(dif,[0,-5/3,-55/18,-65/108],atol=1e-12)
    np.testing.assert_allclose(dea,[0,-10/9,-65/27,-65/54],atol=1e-12)
    np.testing.assert_allclose(hist,[0,-10/9,-35/27,65/54],atol=1e-12)
    np.testing.assert_allclose(p._rsi_series([100.,90.,80.,90.],2),[50,0,0,50])
    data=hand_frame()
    before=macd_values(data.Close,2,3,2)
    data.iloc[25:,3]=10000
    after=macd_values(data.Close,2,3,2)
    for a,b in zip(before,after):np.testing.assert_array_equal(a[:25],b[:25])


