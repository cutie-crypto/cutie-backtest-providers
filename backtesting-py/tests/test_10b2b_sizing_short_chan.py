"""10-B2b: risk sizing for the five short templates (MACD/RSI bearish divergence, double top,
head-and-shoulders top, Chan third sell) and Chan third buy.

Risk distance = |actual next-open fill - the template's own initial stop frozen at the signal|;
direction only signs the order quantity. Expected numbers below are hand arithmetic
(capital 10000, fee/slippage 0 unless stated), never generated by the code under test.
"""
from decimal import Decimal

import pytest
from fastapi.testclient import TestClient

import _10b2b_cases as c
import cutie_backtesting_provider as p
from strategy_position_sizing import POSITION_SIZE_KEYS

TOOLS = tuple(c.CASES)
RISK = dict(position_size_risk_pct=1, position_size_qty_step=0.001)
REPORT_KEY = dict(macd_bearish_divergence='divergence', rsi_bearish_divergence='divergence',
                  double_top='top_pattern', head_shoulders='top_pattern', chan_3sell='chan', chan_3buy='chan')


def fills(body):
    return body['raw_report']['position_sizing']['fills']


def signed_qty(trade):
    return Decimal(trade['qty']) * (-1 if trade['side'] == 'short' else 1)


