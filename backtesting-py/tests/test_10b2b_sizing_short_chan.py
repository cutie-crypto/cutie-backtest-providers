# Leverage 3, chan third sell (fill 115, stop 126.126). Risk 29%: 2900 / 11.126 = 260.6507.. -> 260.650.
#  margin = 260.65 * 115 / 3 = 9991.58333..;  fee 10 bps cost = 260.65 * 115 * 0.001 = 29.97475
#  fee 0:  margin 9991.58 <= 10000 -> filled.  fee 10: 9991.58 + 29.97 = 10021.56 > 10000 -> rejected.
def test_leverage3_short_reserves_margin_and_fees(monkeypatch, tmp_path):
    params = dict(position_size_risk_pct=29, position_size_qty_step=0.001, leverage=3)
    body = c.post(monkeypatch, tmp_path, 'chan_3sell', params)
    assert body['result_status'] == 'success', body
    [fill] = fills(body)
    assert (fill['fill_price'], fill['qty']) == ('115.0', '260.650')
    assert Decimal(fill['margin']) == Decimal('260.650') * Decimal('115.0') / 3
    assert [signed_qty(t) for t in body['trades']] == [Decimal('-260.650')]
    fee = c.post(monkeypatch, tmp_path, 'chan_3sell', params, fee='10')
    assert fee['trades'] == []
    assert [r['reason'] for r in fee['raw_report']['position_sizing']['rejections']] == ['insufficient_funds_after_fees']


def liquidation_frame():
    data = c.CASES['chan_3sell'][0]()
    data.iloc[14, :4] = [160, 161, 159, 160]   # gaps over stop 126.126 and liquidation 115 * 4/3
    return data


# Leverage 3 short fill 115: liquidation = 115 * (1 + 1/3) = 153.333.. (mmr 0); bar14 opens 160 => gap.
# Sized qty 8.987 (1%): margin_lost = 8.987 * 115 / 3 = 344.50166..;
# loss_beyond_margin = 8.987 * (160 - 153.333..) = 59.91333..
def test_leverage3_short_liquidation_detail_matches_unsized_basis(monkeypatch, tmp_path):
    sized = c.post(monkeypatch, tmp_path, 'chan_3sell', {**RISK, 'leverage': 3}, data=liquidation_frame())
    plain = c.post(monkeypatch, tmp_path, 'chan_3sell', {'leverage': 3}, data=liquidation_frame())
    assert sized['result_status'] == plain['result_status'] == 'success', (sized, plain)
    a, b = sized['raw_report']['isolated_risk'], plain['raw_report']['isolated_risk']
    assert a['leverage'] == b['leverage'] == 3
    assert a['liquidation_count'] == b['liquidation_count'] == 1
    assert a['liquidation_gap_count'] == b['liquidation_gap_count'] == 1
    [da], [db] = a['liquidations'], b['liquidations']
    for key in ('seq', 'liquidation_price', 'fill_price', 'liquidation_gap'):
        assert da[key] == db[key], key
    liq = Decimal(115) * 4 / 3
    assert abs(Decimal(da['liquidation_price']) - liq) < Decimal('1e-6')
    assert Decimal(da['fill_price']) == 160
    qty = Decimal('8.987')
    assert abs(Decimal(da['margin_lost']) - qty * 115 / 3) < Decimal('1e-6')
    assert abs(Decimal(da['loss_beyond_margin']) - qty * (160 - liq)) < Decimal('1e-6')
    assert [signed_qty(t) for t in sized['trades']] == [-qty]


def test_six_templates_left_pending_list_and_others_still_reject(monkeypatch):
    monkeypatch.setattr(p, 'AUTH_TOKEN', '')
    monkeypatch.setattr(p, '_fetch_ohlcv', lambda *a, **k: pytest.fail('pending tool fetched data'))
    wired = {'local.backtesting_py.' + n for n in TOOLS}
    assert wired.isdisjoint(p.POSITION_SIZING_PENDING_TOOLS)
    assert wired <= p.POSITION_SIZING_TEMPLATE_STOP_TOOLS
    for tool in wired:
        assert POSITION_SIZE_KEYS <= set(p.TOOL_SPECS[tool]['param_schema_properties']), tool
    assert len(p.POSITION_SIZING_PENDING_TOOLS) == 14
