def test_short_isolated_risk_arbitration_and_accounting(name,case):
    from decimal import Decimal
    data=hand_frame()
    # Fill100, leverage5 => short liquidation120, frozen stop122.122 beyond it.
    if case=='gap_liquidation':
        data.iloc[25,:4]=[130,131,129,130]
    else:
        data.iloc[24,:4]=[100,125,99,106]
    leverage=2 if case=='closer_stop' else 5
    result=http_response(name,dict(leverage=leverage,position_size_pct=10,**({'rsi_exit_below':0} if name.startswith('rsi') else {})),data)
    risk=result['raw_report']['isolated_risk']
    assert result['trades'][0]['side']=='short'
    if case=='closer_stop':
        # L2 liquidation150; closer122.122 stop wins, settled at next open90.
        assert risk['liquidation_count']==0
        assert result['raw_report']['divergence']['exits'][0]['reason']=='stop_loss'
        assert result['trades'][0]['exit_price']=='90'
    else:
        price='130' if case=='gap_liquidation' else '120'
        assert risk['liquidation_count']==1
        assert result['trades'][0]['exit_price']==price
        assert risk['liquidations'][0]['liquidation_gap'] is (case=='gap_liquidation')
    trade=result['trades'][0]
    entry,exit,qty=(Decimal(trade[k]) for k in ('entry_price','exit_price','qty'))
    assert Decimal(trade['fee'])==0 and Decimal(trade['slippage'])==0
    assert Decimal(trade['pnl'])==(entry-exit)*qty
    assert Decimal(result['equity_curve'][-1]['equity'])==Decimal('10000')+Decimal(trade['pnl'])
    assert Decimal(result['metrics']['total_return'])==Decimal(trade['pnl'])/Decimal('10000')
    for price_key,time_key in (('entry_price','opened_at'),('exit_price','closed_at')):
        bar=data.loc[pd.Timestamp(trade[time_key],unit='s')]
        assert Decimal(str(bar.Low))<=Decimal(trade[price_key])<=Decimal(str(bar.High))
    assert 'funding' in str(result['assumptions']).lower()


