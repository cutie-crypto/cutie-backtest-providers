@pytest.mark.parametrize('kind', ['macd','rsi'])
def test_unconfirmed_second_high_never_signals_and_prefix_is_causal(kind):
    data = hand_frame()
    dif = [1.]*len(data)
    dif[22] = -1.  # Early cross one bar before H2's right N bars have closed.
    dif[24:] = [-1.]*(len(data)-24)
    full, _ = facts(data, kind=kind, dif=dif)
    assert all(full[i] is None for i in (21,22))
    assert full[23 if kind=='rsi' else 24] is not None
    for end in (21,22,23,24,25,29):
        part, _ = facts(data.iloc[:end], kind=kind, dif=dif[:end])
        assert part == full[:end]
    changed = data.copy()
    changed.iloc[25:, :4] = [500,501,499,500]
    assert facts(changed, kind=kind, dif=dif)[0][:25] == full[:25]


