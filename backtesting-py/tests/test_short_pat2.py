def test_bullish_builders_and_catalog_source_bytes_unchanged():
    import subprocess
    import ast
    original=subprocess.check_output(['git','show','32ae030:backtesting-py/cutie_backtesting_provider.py'],text=True)
    current=Path(p.__file__).read_text()
    def sections(source):
        result={}
        for node in ast.walk(ast.parse(source)):
            if isinstance(node,ast.FunctionDef) and node.name in ('_build_divergence','_build_macd_bullish_divergence','_build_rsi_bullish_divergence'):
                start=min([node.lineno]+[d.lineno for d in node.decorator_list])
                result[node.name]=''.join(source.splitlines(keepends=True)[start-1:node.end_lineno])
            if isinstance(node,ast.Dict):
                for key,value in zip(node.keys,node.values):
                    if isinstance(key,ast.Constant) and key.value in ('local.backtesting_py.macd_bullish_divergence','local.backtesting_py.rsi_bullish_divergence'):
                        result[key.value]=ast.get_source_segment(source,value)
        return result
    assert len(sections(current))==5
    assert sections(current)==sections(original)
